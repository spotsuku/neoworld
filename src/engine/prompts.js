export function rosterText(agents, challenges) {
  const heroes = agents.slice(0, 5).map(a =>
    `${a.id}(${a.name},${a.age}):${a.persona}目標:${a.goal} 幸福:${a.happiness} 余白:${a.slack} 弱点:${weakest(a)}`
  ).join("\n");
  const others = agents.slice(5).filter((_, i) => i % 4 === 0).map(a => `${a.id}(${a.name},${a.age}):${a.persona}幸福:${a.happiness}`).join("\n");
  const ch = challenges.filter(c => c.status === "active").map(c => `「${c.name}」(${c.ownerName},進捗${c.progress}/3,応援${c.totalSupport}pt)`).join(",") || "なし";
  const done = challenges.filter(c => c.status === "done").slice(-5).map(c => c.name).join(",") || "なし";
  return `【主要住民】\n${heroes}\n【その他住民(抜粋)】\n${others}\n【進行中の挑戦】${ch}\n【実現済みの文化】${done}`;
}
